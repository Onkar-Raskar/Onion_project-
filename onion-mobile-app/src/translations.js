export const getTranslation = (lang, key, params = {}) => {
  const dict = translations[lang] || translations.en;
  let text = dict[key] || translations.en[key] || key;
  Object.keys(params).forEach(p => {
    text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
  });
  return text;
};
